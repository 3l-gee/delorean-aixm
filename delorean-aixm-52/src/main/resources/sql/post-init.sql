CREATE INDEX IF NOT EXISTS IDX_SURFACE_VIEW_GEOM ON GML.SURFACE_VIEW USING GIST (GEOM);

CREATE MATERIALIZED VIEW GML.AIXM_SURFACE_PT_VIEW AS (
	SELECT
        GML.AIXM_SURFACE_PT.HJID,
		GML.SURFACE_VIEW.ID,
        AIXM_SURFACE.HORIZONTALACCURACY,
        AIXM_SURFACE.HORIZONTALACCURACY_UOM,
        AIXM_SURFACE.HORIZONTALACCURACY_ACCURACY,
        AIXM_SURFACE.HORIZONTALACCURACY_NILREASON,
		NOTE_P.HJID AS ANNOTATION_HJID,
		GML.SURFACE_VIEW.GEOM
	FROM
		GML.AIXM_SURFACE_PT
		INNER JOIN GML.AIXM_SURFACE ON AIXM_SURFACE_PT.SURFACE_HJID = AIXM_SURFACE.HJID
		INNER JOIN GML.SURFACE_VIEW ON AIXM_SURFACE.HJID = SURFACE_VIEW.HJID
		LEFT JOIN GML.AIXM_SURFACE_ANNOTATION_LINK ON AIXM_SURFACE.HJID = AIXM_SURFACE_ANNOTATION_LINK.AIXM_SURFACE_HJID
		LEFT JOIN NOTE.NOTE_P ON AIXM_SURFACE_ANNOTATION_LINK.ANNOTATION_HJID = NOTE_P.HJID
);

